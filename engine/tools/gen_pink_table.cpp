// Generate engine/src/pink_table.inc: N_pink(x) for x = -70 .. +3 LUFS in 0.5 LU steps (MATH §12.2).
// Diotic pink noise (-3 dB/octave, band-limited 20 Hz - 15 kHz), 30 s at 32 kHz, deterministic generator
// (xorshift64, seed 0x5AB1E), mean fast-model LTL after the first 2 s, under D_cal = 89 dB.
// Usage: gen_pink_table <out.inc>
#include <cstdint>
#include <cstdio>
#include <vector>

#include "../src/dsp.h"
#include "sable/analyzer.h"
#include "sable/dmath.h"
#include "sable/perceptual.h"

int main(int argc, char** argv) {
  if (argc < 2) return 2;
  constexpr int kFs = 32000;
  constexpr std::size_t kN = 1u << 20;
  constexpr std::size_t kLen = 30u * kFs;
  std::uint64_t s = 0x5AB1E;
  std::vector<double> re(kN), im(kN, 0.0);
  for (auto& v : re) {
    s ^= s << 13; s ^= s >> 7; s ^= s << 17;
    v = static_cast<double>(s >> 11) / 9007199254740992.0 - 0.5;
  }
  sable::dsp::Fft<double> fft(kN);
  fft.forward(re.data(), im.data());
  for (std::size_t k = 0; k < kN; ++k) {  // shape: |X| ~ 1/sqrt(f) inside 20 Hz - 15 kHz (both halves)
    const std::size_t kk = k <= kN / 2 ? k : kN - k;
    const double f = static_cast<double>(kk) * kFs / static_cast<double>(kN);
    const double g = (f >= 20.0 && f <= 15000.0) ? 1.0 / sable::dm::sqrt(f) : 0.0;
    re[k] *= g;
    im[k] *= -g;  // conjugate for the inverse transform via forward FFT
  }
  fft.forward(re.data(), im.data());
  std::vector<float> x(2 * kLen);
  double ms = 0.0;
  for (std::size_t i = 0; i < kLen; ++i) ms += re[i] * re[i];
  const double norm = 0.1 / sable::dm::sqrt(ms / kLen);
  for (std::size_t i = 0; i < kLen; ++i) x[2 * i] = x[2 * i + 1] = static_cast<float>(re[i] * norm);

  sable::Analyzer an(kFs, 2, {1.0, 1.0});
  an.push(x.data(), kLen);
  const double l0 = *an.finish().integratedLufs;

  std::FILE* o = std::fopen(argv[1], "w");
  if (!o) return 2;
  std::fprintf(o, "// GENERATED by engine/tools/gen_pink_table -- do not edit. MATH §12.2.\n");
  std::fprintf(o, "// N_pink(x): mean fast-model LTL (sone) of diotic pink noise at x LUFS, D_cal = 89 dB.\n#pragma once\n");
  std::fprintf(o, "namespace sable::tables {\ninline constexpr double kPinkLufsStart = -70.0, kPinkLufsStep = 0.5;\n");
  std::fprintf(o, "inline constexpr double kPinkSone[147] = {\n");
  for (int i = 0; i < 147; ++i) {
    const double target = -70.0 + 0.5 * i;
    sable::FastLoudness m(kFs, 2, target - l0);
    m.push(x.data(), kLen);
    const auto r = m.finish();
    double sum = 0.0;
    std::size_t n = 0;
    for (std::size_t f = 0; f < r.ltlPerFrame.size(); ++f)
      if (static_cast<double>(f) * r.frameSeconds >= 2.0) { sum += r.ltlPerFrame[f]; ++n; }
    std::fprintf(o, "    %.17g,%s", sum / static_cast<double>(n), (i % 4 == 3) ? "\n" : "");
    std::fprintf(stderr, "x=%.1f LUFS -> %.6g sone\n", target, sum / static_cast<double>(n));
  }
  std::fprintf(o, "\n};\n}  // namespace sable::tables\n");
  std::fclose(o);
  return 0;
}
