// Perceptual lens: time-varying loudness (Moore-Glasberg-Schlittenlacher TVL 2018). MATH §10-§12.
#pragma once

#include <cstddef>
#include <optional>
#include <string>
#include <vector>

namespace sable {

// Per-100 ms sub-block series on the input timeline (sub-block m = [m*H, (m+1)*H) input samples).
struct PerceptualSeries {
  std::vector<std::optional<double>> stlSone;  // mean short-term loudness (binaural, sones)
  std::vector<std::optional<double>> ltlSone;  // mean long-term loudness (binaural, sones)
  std::vector<double> ltlPerFrame;             // native-frame LTL (1 ms reference / 4 ms fast), for validation
  double frameSeconds = 0.0;
};

// Fast model shipped on the phone (MATH §11). Streams; deterministic (sable::dm, fixed order).
class FastLoudness {
 public:
  // prescaleDb: gain applied before analysis (MATH §12.4). dcalDb: RMS SPL of a full-scale sine (MATH §12.1).
  FastLoudness(int sampleRateHz, int channels, double prescaleDb, double dcalDb = 89.0);
  ~FastLoudness();
  FastLoudness(const FastLoudness&) = delete;
  FastLoudness& operator=(const FastLoudness&) = delete;
  void push(const float* interleaved, std::size_t frames);
  PerceptualSeries finish();

 private:
  struct Impl;
  Impl* impl_;
};

// Perceptual loudness equivalent (MATH §12.3): LUFS of diotic pink noise with the same mean long-term
// loudness under D_cal. Monotone piecewise-linear in (LUFS, log sone). `clamped` is set when outside the table.
double pleFromSone(double sone, bool* clamped = nullptr);

// Host-only full-resolution reference (MATH §10). Offline; slow. firPath: little-endian doubles of the
// 4097-tap free-field filter (generated by tools/perceptual/gen_tables.py).
PerceptualSeries referenceLoudness(const std::vector<float>& interleaved, int sampleRateHz, int channels,
                                   double prescaleDb, const std::string& firPath, double dcalDb = 89.0);

}  // namespace sable
