"""Generate engine/src/perceptual_tables.inc from the TVL 2018 reference (Moore, Glasberg & Schlittenlacher).

Inputs (local, not committed): the authors' tv2018matlab.zip contents. Outputs:
  - engine/src/perceptual_tables.inc : model tables (threshold, alpha, A) and the free-field outer/middle-ear
    power response sampled at the exact FFT bin frequencies used by the fast model (MATH §11 F2/F3).
  - <refs>/ff_32000.f64 : the full 4097-tap FIR (little-endian doubles) for the host-only reference model.
Usage: py -3 tools/perceptual/gen_tables.py [path/to/"TVL 2018"/tv2018]
"""
import os
import re
import sys

import numpy as np
import scipy.io as sio

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/dev/sable-refs/tvl2018/src/TVL 2018/tv2018")


def numbers(text):
    return [float(x) for x in re.findall(r"-?\d+\.\d+|-?\d+", text)]


def matrix_rows(m_file, var):
    t = open(os.path.join(SRC, "functions", m_file), encoding="latin-1").read()
    body = t[t.index(var):]
    body = body[body.index("[") + 1: body.index("]")]
    rows = [numbers(r) for r in body.split(";")]
    return [r for r in rows if r]


def fmt(name, vals, per=6):
    out = [f"inline constexpr double {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(repr(float(v)) for v in vals[i:i + per]) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    thr = matrix_rows("ExcitationThreshold_TVL.m", "Threshold =")
    alpha = matrix_rows("get_Alpha.m", "TableG2Alpha =")
    a_tab = matrix_rows("get_A.m", "TableG2A =")
    assert len(thr[0]) == len(thr[1]) == 15, thr
    assert len(alpha[0]) == len(alpha[1]) == 6, alpha
    assert len(a_tab[0]) == len(a_tab[1]) == 90, [len(r) for r in a_tab]

    h = np.asarray(sio.loadmat(os.path.join(SRC, "transfer functions", "ff_32000.mat"))["vecCoefficients"]).ravel().astype("<f8")
    assert len(h) == 4097 and int(np.argmax(np.abs(h))) == 2048
    refs = os.path.dirname(os.path.dirname(os.path.dirname(SRC)))
    h.tofile(os.path.join(refs, "ff_32000.f64"))

    # Power response |H(f)|^2 at the fast model's bin frequencies (MATH §11 F3):
    #   band A: 8 kHz, N=512 (15.625 Hz), band B: 32 kHz, N=512 (62.5 Hz), band C: 32 kHz, N=128 (250 Hz).
    def power_at(freqs):
        w = 2 * np.pi * np.asarray(freqs) / 32000.0
        n = np.arange(len(h)) - 2048  # zero-phase about the centre tap
        H = np.array([np.sum(h * np.cos(wi * n)) for wi in w])  # symmetric FIR -> real response
        return H * H
    fa = np.arange(0, 257) * 8000.0 / 512
    fb = np.arange(0, 257) * 32000.0 / 512
    fc = np.arange(0, 65) * 32000.0 / 128
    sym = float(np.max(np.abs(h - h[::-1])))

    out = [
        "// GENERATED by tools/perceptual/gen_tables.py -- do not edit.",
        "// Model tables from the TVL 2018 reference code by B.C.J. Moore, B.R. Glasberg and J. Schlittenlacher",
        "// (University of Cambridge; free for research use). Free-field outer/middle-ear power response sampled",
        f"// at the fast model's FFT bin frequencies (FIR symmetry error {sym:.1e}). MATH §10.1, §11.",
        "#pragma once",
        "namespace sable::tables {",
        fmt("kThresholdHz", thr[0]), fmt("kThresholdDb", thr[1]),
        fmt("kAlphaGdb", alpha[0]), fmt("kAlphaValue", alpha[1]),
        fmt("kAGdb", a_tab[0]), fmt("kAValue", a_tab[1]),
        fmt("kEarPowerBandA", power_at(fa)), fmt("kEarPowerBandB", power_at(fb)), fmt("kEarPowerBandC", power_at(fc)),
        "}  // namespace sable::tables",
        "",
    ]
    dst = os.path.join(REPO, "engine", "src", "perceptual_tables.inc")
    open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("wrote", dst, "and", os.path.join(refs, "ff_32000.f64"))


if __name__ == "__main__":
    main()
