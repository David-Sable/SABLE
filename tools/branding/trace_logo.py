"""Regenerates the SABLE lion mark from tools/branding/lion_source.webp (Dana's AI-generated artwork).

    python tools/branding/trace_logo.py          (needs: pip install pillow vtracer)

Writes android/app/src/main/res/drawable/lion_mark.xml (in-app mark) and ic_launcher_foreground.xml (launcher icon,
lion 56 dp wide inside the 66 dp safe circle). One <path> per traced shape: Android rejects resource strings longer
than 32,767 characters, so never merge them into one path.
"""
import os, re, tempfile
from PIL import Image
import vtracer

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'tools', 'branding', 'lion_source.webp')
OUT = os.path.join(ROOT, 'android', 'app', 'src', 'main', 'res', 'drawable')
FILL = '#F2EEE6'      # warm white (SableColors.textPrimary)
ICON_WIDTH = 56.0     # dp of the 108 dp adaptive canvas

def trace():
    im = Image.open(SRC).convert('L')
    box = im.point(lambda v: 255 if v > 128 else 0).getbbox()          # the white lion on black
    im = im.crop(box)
    im = im.resize((im.width * 2, im.height * 2), Image.LANCZOS)        # smoother curves
    bw = im.point(lambda v: 0 if v > 128 else 255).convert('RGB')       # lion = black foreground for the tracer
    tmp = tempfile.mkdtemp()
    png, svg = os.path.join(tmp, 'lion.png'), os.path.join(tmp, 'lion.svg')
    bw.save(png)
    vtracer.convert_image_to_svg_py(png, svg, colormode='binary', mode='spline', filter_speckle=8, corner_threshold=60,
                                    length_threshold=4.0, splice_threshold=45, path_precision=1)
    s = open(svg).read()
    w, h = (int(x) for x in re.search(r'width="(\d+)" height="(\d+)"', s).groups())
    paths = []
    for m in re.finditer(r'<path([^>]*)/>', s):
        a = m.group(1)
        d = re.search(r' d="([^"]*)"', a).group(1)
        tx, ty = map(float, re.search(r'translate\(([-\d.]+),([-\d.]+)\)', a).groups())
        out, nums = [], []
        def flush():
            for i in range(0, len(nums), 2):
                out.append(f'{round(nums[i] + tx):d},{round(nums[i + 1] + ty):d}')
        for t in re.findall(r'[MCZ]|-?\d*\.?\d+', d):
            if t in 'MCZ':
                flush(); nums.clear(); out.append(t)
            else:
                nums.append(float(t))
        flush()
        paths.append(' '.join(out).replace(' Z', 'Z'))
    return w, h, paths

def main():
    w, h, paths = trace()
    assert max(len(p) for p in paths) < 32000, 'a path is too long for an Android resource string'
    els = '\n'.join(f'    <path android:fillColor="{FILL}" android:pathData="{p}" />' for p in paths)
    with open(os.path.join(OUT, 'lion_mark.xml'), 'w', encoding='utf8') as f:
        f.write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- SABLE mark: the white lion (owner's AI-generated artwork, traced to vector with vtracer). Generated by
     tools/branding/trace_logo.py: don't hand-edit. One <path> per shape (Android caps resource strings at 32,767 chars). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="60dp" android:height="48dp" android:viewportWidth="{w}" android:viewportHeight="{h}">
{els}
</vector>
''')
    k = ICON_WIDTH / w
    tx, ty = (108 - ICON_WIDTH) / 2, (108 - h * k) / 2
    grp = '\n'.join('    ' + l for l in els.split('\n'))
    with open(os.path.join(OUT, 'ic_launcher_foreground.xml'), 'w', encoding='utf8') as f:
        f.write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- The white lion centred in the 108 dp adaptive-icon canvas, {ICON_WIDTH:g} dp wide (inside the 66 dp safe circle).
     Generated by tools/branding/trace_logo.py: don't hand-edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="{tx:.4f}" android:translateY="{ty:.4f}" android:scaleX="{k:.6f}" android:scaleY="{k:.6f}">
{grp}
    </group>
</vector>
''')
    print(f'{len(paths)} shapes, longest {max(len(p) for p in paths)} chars')

if __name__ == '__main__':
    main()
